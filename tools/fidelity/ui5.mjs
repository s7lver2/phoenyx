import { chromium } from 'playwright-core';
const port = process.argv[2];
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--enable-gpu','--use-angle=default','--ignore-gpu-blocklist'] });
const page = await (await b.newContext({ viewport: { width: 1600, height: 778 }, deviceScaleFactor: 1.25 })).newPage();
await page.goto(`http://localhost:${port}/`);
await page.waitForTimeout(2500);
await page.getByText('CONTINUE', { exact: true }).click().catch(()=>{});
await page.getByText('PLAY', { exact: true }).first().waitFor({ timeout: 90000 }).catch(() => {});
await page.getByText('LATER', { exact: true }).first().click().catch(() => {});
await page.getByText('PLAY', { exact: true }).first().click();
await page.waitForTimeout(2000);
await page.getByText('PLAY SOLO').first().click();
await page.waitForTimeout(14000);
await page.screenshot({ path: `E:/tmp/dpr-pl-${port}.png` });
await page.keyboard.press('Escape');
await page.waitForTimeout(2000);
await page.screenshot({ path: `E:/tmp/dpr-pa-${port}.png` });
console.log(port, await page.evaluate(() => document.querySelector('.br')?.getAttribute('data-screen')));
await b.close();
